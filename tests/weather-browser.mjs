import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const b=await chromium.launch({args:['--no-sandbox']});
const c=await b.newContext({viewport:{width:390,height:844}});
let unavailable=false;
const fetchedAt=new Date().toISOString();
const payload={status:'connected',message:null,fetchedAt,data:{source:'กรมอุตุนิยมวิทยา',kind:'พยากรณ์รายชั่วโมง',requestedLocation:{name:'พื้นที่ทดสอบ',lat:16.7,lon:103.7},modelLocation:{lat:16.7,lon:103.7},forecasts:Array.from({length:24},(_,i)=>({time:new Date(Date.now()+(i+1)*3600000).toISOString(),rain:i===0?0:null,windSpeed:3,windDirection:90,temperature:28,condition:3}))}};
await c.route('**/functions/v1/tmd-weather',r=>r.fulfill({status:200,contentType:'application/json',headers:{'Access-Control-Allow-Origin':'*','Access-Control-Allow-Headers':'apikey'},body:JSON.stringify(unavailable?{status:'unavailable',message:'กรมอุตุฯ ไม่ยอมรับ Token กรุณาตรวจสอบ TMD_API_TOKEN',data:null}:payload)}));
const p=await c.newPage();
await p.goto('http://localhost:3001');
const panel=p.getByRole('region',{name:'พยากรณ์อากาศกรมอุตุนิยมวิทยา'});
await panel.getByText('เชื่อม API จริงแล้ว',{exact:true}).waitFor();
assert.match(await panel.textContent(),/ข้อมูลพยากรณ์จริง/);
assert.match(await panel.textContent(),/ไม่มีข้อมูล/);
assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth),390);
await p.getByRole('button',{name:'เพิ่มเติม',exact:true}).last().click();
await p.getByRole('button',{name:'การเชื่อมต่อ API',exact:true}).click();
await panel.getByRole('button',{name:'ดูทั้งหมด 24 ชั่วโมง'}).click();
assert.equal(await panel.locator('tbody tr').count(),24);
unavailable=true;
await panel.getByRole('button',{name:'อัปเดตพยากรณ์อากาศ'}).click();
await panel.getByText('ข้อมูลเดิม · ยังไม่อัปเดต',{exact:true}).waitFor();
await p.evaluate(()=>navigator.serviceWorker.ready);
await p.waitForFunction(()=>!!navigator.serviceWorker.controller);
await p.reload();
await panel.waitFor();
await p.waitForTimeout(800);
await c.setOffline(true);await p.reload();
await panel.getByText('ออฟไลน์ · ข้อมูลที่เก็บไว้',{exact:true}).waitFor({timeout:10000});
assert.match(await panel.textContent(),/ดึงข้อมูลสำเร็จล่าสุด/);
assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth),390);
console.log('PASS: Thai forecast display, mobile layout, 24-hour expansion, upstream error retains data as stale, offline reload shows cached forecast');
await b.close();

import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create table auth.users(id uuid primary key,email_confirmed_at timestamptz default now()); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('app.user_id',true),'')::uuid$$; create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]); create table storage.objects(id uuid primary key,name text,bucket_id text); create function storage.foldername(name text) returns text[] language sql as $$select string_to_array(name,'/')$$;`);
await db.exec(fs.readFileSync('supabase/schema.sql','utf8').replace('create extension if not exists pgcrypto;',''));
await db.exec(fs.readFileSync('supabase/line-webhook.sql','utf8'));
const org = '33333333-3333-4333-8333-333333333333';
const group = 'C'+'a'.repeat(32);
await db.query('insert into organizations(id,name) values($1,$2)',[org,'ศูนย์ทดสอบ LINE']);
const call = async (id,action) => (await db.query('select record_line_group_event($1,$2,$3,$4) as result',[id,org,group,action])).rows[0].result;
assert.equal(await call('event-1','join'),true);
assert.equal(await call('event-1','join'),false);
assert.equal((await db.query('select count(*)::int as count from line_group_connections')).rows[0].count,1);
assert.equal((await db.query('select enabled from line_group_connections')).rows[0].enabled,false);
await call('event-2','leave');
assert.equal((await db.query('select available from line_group_connections')).rows[0].available,false);
await call('event-3','connect');
const row = (await db.query('select * from line_group_connections')).rows[0];
assert.equal(row.available,true); assert.equal(row.enabled,false);
assert.equal((await db.query("select has_function_privilege('authenticated','record_line_group_event(text,uuid,text,text)','EXECUTE') as permitted")).rows[0].permitted,false);
assert.equal((await db.query("select has_table_privilege('anon','line_group_connections','SELECT') as permitted")).rows[0].permitted,false);
await db.exec('set role authenticated');
assert.equal((await db.query('select * from line_group_connections')).rows.length,0);
await db.exec('reset role');
await db.close();
console.log('LINE event deduplication, default-disabled group, leave/rejoin and restricted access passed.');

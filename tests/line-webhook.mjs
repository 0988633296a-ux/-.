import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { webcrypto } from 'node:crypto';
const source = ts.transpileModule(fs.readFileSync('supabase/functions/line-webhook/signature.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { validSignature, groupEvent } = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const secret = 'test-secret-only';
const body = new TextEncoder().encode('{"events":[]}');
const key = await webcrypto.subtle.importKey('raw',new TextEncoder().encode(secret),{name:'HMAC',hash:'SHA-256'},false,['sign']);
const signature = Buffer.from(await webcrypto.subtle.sign('HMAC',key,body)).toString('base64');
assert.equal(await validSignature(body,signature,secret),true);
assert.equal(await validSignature(new TextEncoder().encode('{"events": []}'),signature,secret),false);
assert.equal(await validSignature(body,signature,'wrong-secret'),false);
assert.equal(await validSignature(body,'',secret),false);
assert.equal(await validSignature(body,'not base64!',secret),false);
const sourceGroup = {type:'group',groupId:'C'+'a'.repeat(32)};
assert.equal(groupEvent({type:'join',source:sourceGroup}).action,'join');
assert.equal(groupEvent({type:'message',source:sourceGroup,message:{type:'text',text:'เชื่อม ปภ.'}}).action,'connect');
assert.equal(groupEvent({type:'message',source:sourceGroup,message:{type:'text',text:'ข้อมูลผู้บาดเจ็บ'}}),null);
assert.equal(groupEvent({type:'join',source:{type:'user',userId:'U'+'a'.repeat(32)}}),null);
assert.equal(groupEvent({type:'join',source:{type:'group',groupId:'invalid'}}),null);
console.log('LINE HMAC verification, modified-body rejection and group-only registration passed.');
